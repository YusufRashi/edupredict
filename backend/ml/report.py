"""Turn training metadata into a Markdown report and evaluation figures.

Nothing here is typed in by hand: every number comes from metadata.json.
"""

from __future__ import annotations

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import seaborn as sns  # noqa: E402

from ml.config import FIGURES_DIR, REPORTS_DIR  # noqa: E402

PURPLE = "#635BDB"
INK = "#111827"
MUTED = "#64748B"


def _figures(metadata: dict) -> None:
    FIGURES_DIR.mkdir(parents=True, exist_ok=True)
    sns.set_theme(style="white", rc={"axes.spines.top": False, "axes.spines.right": False,
                                     "text.color": INK, "axes.labelcolor": MUTED})
    for key, stage in metadata["stages"].items():
        classifier = stage["classifier"]
        cm = classifier["confusion_matrix"]
        fig, axes = plt.subplots(1, 3, figsize=(11, 3.4))
        sns.heatmap([[cm["tn"], cm["fp"]], [cm["fn"], cm["tp"]]], annot=True, fmt="d",
                    cmap=sns.light_palette(PURPLE, as_cmap=True), cbar=False, ax=axes[0],
                    xticklabels=["Pass", "Below pass"], yticklabels=["Pass", "Below pass"])
        axes[0].set(title="Confusion matrix (test)", xlabel="Predicted", ylabel="Actual")

        roc = classifier["roc_curve"]
        axes[1].plot([p["fpr"] for p in roc], [p["tpr"] for p in roc], color=PURPLE, linewidth=2)
        axes[1].plot([0, 1], [0, 1], color=MUTED, linestyle="--", linewidth=1)
        axes[1].set(title=f"ROC (AUC {classifier['test']['roc_auc']:.3f})",
                    xlabel="False positive rate", ylabel="True positive rate")

        calibration = classifier["calibration"]
        axes[2].plot([p["predicted"] for p in calibration], [p["observed"] for p in calibration],
                     marker="o", color=PURPLE, linewidth=2)
        axes[2].plot([0, 1], [0, 1], color=MUTED, linestyle="--", linewidth=1)
        axes[2].set(title="Calibration (test)", xlabel="Predicted probability",
                    ylabel="Observed rate")
        fig.suptitle(f"{stage['label']}: {classifier['algorithm']}", fontweight="bold")
        fig.tight_layout()
        fig.savefig(FIGURES_DIR / f"evaluation_{key}.png", dpi=130, bbox_inches="tight")
        plt.close(fig)


def _table(headers: list[str], rows: list[list]) -> str:
    lines = ["| " + " | ".join(headers) + " |", "|" + " --- |" * len(headers)]
    lines += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(lines)


def build_markdown(metadata: dict) -> str:
    dataset = metadata["dataset"]
    out = [
        "# EduPredict model report", "",
        "> Generated by `python -m ml.train`. Do not edit by hand.", "",
        f"**Version:** `{metadata['version']}`  ",
        f"**Trained:** {metadata['trained_at']}  ",
        f"**Dataset:** {dataset['name']} ({dataset['licence']}), DOI {dataset['doi']}  ",
        f"**Target:** {metadata['target']['description']}", "",
        "## Splits", "",
        _table(["Split", "Rows", "Student groups", "Below-pass rate"],
               [[k, v["rows"], v["student_groups"], f"{v['at_risk_rate']:.1%}"]
                for k, v in dataset["splits"].items()]),
        "",
        "## Results on the held-out test set", "",
        "Positive class: final grade below the pass mark. The threshold was tuned on validation "
        "data, and the baseline uses no features.", "",
        _table(
            ["Stage", "Algorithm", "Threshold", "Accuracy", "Precision", "Recall", "F1",
             "ROC-AUC", "PR-AUC", "Brier", "Baseline PR-AUC"],
            [[s["label"], s["classifier"]["algorithm"],
              s["classifier"]["risk_bands"]["moderate_from"],
              *[s["classifier"]["test"][m] for m in
                ("accuracy", "precision", "recall", "f1", "roc_auc", "pr_auc", "brier")],
              s["classifier"]["baseline_test"]["pr_auc"]]
             for s in metadata["stages"].values()],
        ),
        "",
        _table(
            ["Stage", "Algorithm", "MAE", "MSE", "RMSE", "R²", "MAE without G3=0",
             "80% interval (±)", "Interval coverage", "Baseline RMSE"],
            [[s["label"], s["regressor"]["algorithm"],
              *[s["regressor"]["test"][m] for m in ("mae", "mse", "rmse", "r2")],
              s["regressor"]["test_excluding_zero_finals"]["mae"],
              s["regressor"]["interval_half_width_80"],
              f"{s['regressor']['interval_coverage_test']:.1%}",
              s["regressor"]["baseline_test"]["rmse"]]
             for s in metadata["stages"].values()],
        ),
        "",
        "## Cost of excluding sensitive features", "",
        "The same algorithm refitted with every excluded column, scored for comparison only. "
        "This variant is never saved or served.", "",
        _table(
            ["Stage", "Deployed PR-AUC", "All-features PR-AUC", "Deployed RMSE",
             "All-features RMSE"],
            [[s["label"], s["classifier"]["test"]["pr_auc"],
              s["classifier"]["all_features_benchmark_test"]["pr_auc"],
              s["regressor"]["test"]["rmse"],
              s["regressor"]["all_features_benchmark_test"]["rmse"]]
             for s in metadata["stages"].values()],
        ),
        "",
    ]
    for key, stage in metadata["stages"].items():
        out += [f"## Stage detail: {stage['label']}", "", stage["description"], "",
                f"![Evaluation](figures/evaluation_{key}.png)", "",
                "### Classifier comparison (validation split)", "",
                _table(["Algorithm", "CV PR-AUC", "±", "Val PR-AUC", "Val ROC-AUC", "Val F1@0.5",
                        "Selected"],
                       [[r["algorithm"], r["cv_mean"], r["cv_std"], r["validation"]["pr_auc"],
                         r["validation"]["roc_auc"], r["validation"]["f1"],
                         "yes" if r["selected"] else ""]
                        for r in stage["classifier"]["comparison"]]),
                "", "### Regressor comparison (validation split)", "",
                _table(["Algorithm", "CV RMSE", "±", "Val MAE", "Val RMSE", "Val R²", "Selected"],
                       [[r["algorithm"], r["cv_mean"], r["cv_std"], r["validation"]["mae"],
                         r["validation"]["rmse"], r["validation"]["r2"],
                         "yes" if r["selected"] else ""]
                        for r in stage["regressor"]["comparison"]]),
                "", "### What happened to students in each risk band (test)", "",
                _table(["Band", "Students", "Observed below-pass rate"],
                       [[b["level"], b["students"],
                         "n/a" if b["observed_below_pass_rate"] is None
                         else f"{b['observed_below_pass_rate']:.1%}"]
                        for b in stage["classifier"]["band_outcomes"]]),
                "", "### Fairness audit (test)", "",
                _table(["Attribute", "Group", "n", "Below-pass rate", "Flagged", "Recall", "FPR",
                        "Grade MAE", "Small sample"],
                       [[a["attribute"], g["group"], g["n"], g["actual_below_pass_rate"],
                         g["flagged_rate"], g["recall"], g["false_positive_rate"], g["grade_mae"],
                         "yes" if g["small_sample"] else ""]
                        for a in stage["fairness"] for g in a["groups"]]),
                ""]
    out += ["## Limitations", ""] + [f"- {item}" for item in metadata["limitations"]] + [""]
    return "\n".join(out)


def write_report(metadata: dict) -> None:
    _figures(metadata)
    REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    (REPORTS_DIR / "model_report.md").write_text(build_markdown(metadata), encoding="utf-8")
